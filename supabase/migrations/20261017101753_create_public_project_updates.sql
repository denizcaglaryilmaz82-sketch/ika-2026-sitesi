create table if not exists public.project_updates (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 160),
  body text not null check (char_length(body) between 1 and 3000),
  category text not null default 'Geliştirme' check (char_length(category) between 1 and 40),
  created_at timestamptz not null default now()
);

alter table public.project_updates enable row level security;
revoke all on table public.project_updates from anon, authenticated;
grant select on table public.project_updates to anon, authenticated;

create policy "Public can read project updates"
  on public.project_updates
  for select
  to anon, authenticated
  using (true);
